# Вычисление длины окружности и площади круга по радиусу R

import math

# Ввод радиуса с проверкой на число
try:
    radius = float(input("Введите радиус R: "))
except ValueError:
    print("Ошибка: радиус должен быть числом")
    exit()

# Проверка на неотрицательный радиус
if radius < 0:
    print("Ошибка: радиус не может быть отрицательным")
else:
    # Расчёт длины окружности и площади круга
    length = 2 * math.pi * radius
    area = math.pi * radius ** 2

    # Вывод результатов
    print("Длина окружности: {:.2f}".format(length))
    print("Площадь круга: {:.2f}".format(area))
