# Лабораторная работа №2, вариант 2
# Решение квадратного уравнения ax^2 + bx + c = 0

import math

# Ввод коэффициентов с проверкой на число
try:
    a = float(input("a = "))
    b = float(input("b = "))
    c = float(input("c = "))
except ValueError:
    print("Ошибка: коэффициенты должны быть числами")
    exit()

# Особые случаи: уравнение не является квадратным
if a == 0:
    if b == 0:
        if c == 0:
            print("Бесконечно много решений")
        else:
            print("Нет решений")
    else:
        print("Линейное уравнение, корень x =", -c / b)
else:
    # Обычный случай: считаем дискриминант
    d = b * b - 4 * a * c
    print("Дискриминант D =", d)
    if d > 0:
        x1 = (-b + math.sqrt(d)) / (2 * a)
        x2 = (-b - math.sqrt(d)) / (2 * a)
        print("Два корня: x1 =", x1, "x2 =", x2)
    elif d == 0:
        x = -b / (2 * a)
        print("Один корень: x =", x)
    else:
        print("Корней нет, так как D < 0")
